'use strict';
const {contextBridge,ipcRenderer} = require('electron');
contextBridge.exposeInMainWorld('voxelDesktop', Object.freeze({
  platform: process.platform,
  acquireMicrophone:()=>ipcRenderer.invoke('voxel:microphone-acquire'),
  releaseMicrophone:()=>ipcRenderer.invoke('voxel:microphone-release'),
  publishVoiceInteraction:value=>ipcRenderer.send('voxel:voice-interaction',value),
  chatReady:()=>ipcRenderer.send('voxel:chat-ready'),
  onWakeCommand:callback=>{ipcRenderer.on('voxel:wake-command',(_event,value)=>callback(value));},
  onWakeStatus:callback=>{ipcRenderer.on('voxel:wake-status',(_event,value)=>callback(value));},
  wakeDone:id=>ipcRenderer.send('voxel:wake-done',id),
  toggleWake:()=>ipcRenderer.invoke('voxel:wake-toggle'),
  refreshWake:()=>ipcRenderer.invoke('voxel:wake-refresh'),
  onChatClosing:callback=>{ipcRenderer.on('voxel:chat-closing',()=>callback());},
  closeChat:()=>ipcRenderer.invoke('voxel:close-chat'),
  expandChat:value=>ipcRenderer.invoke('voxel:expand-chat',value),
  onChatAnchor:callback=>{ipcRenderer.on('voxel:chat-anchor',(_event,value)=>callback(value));},
  openSource: url => ipcRenderer.invoke('voxel:open-source',url),
  speakNative: text => ipcRenderer.invoke('voxel:speak',text),
  stopSpeech: () => ipcRenderer.invoke('voxel:stop-speech'),
  openSettings: () => ipcRenderer.invoke('voxel:open-settings'),
  openChat: () => ipcRenderer.invoke('voxel:chat'),
  openMenu: () => ipcRenderer.invoke('voxel:menu'),
  publishBusy: busy => ipcRenderer.send('voxel:busy', busy),
  publishState: state => ipcRenderer.send('voxel:state', state),
  saveSession: id => ipcRenderer.send('voxel:session', id),
  openOllamaDownload: () => ipcRenderer.invoke('voxel:ollama-download'),
  setupList: input => ipcRenderer.invoke('voxel:setup-list',input),
  setupPull: input => ipcRenderer.invoke('voxel:setup-pull',input),
  setupCancel: () => ipcRenderer.invoke('voxel:setup-cancel'),
  setupFinish: input => ipcRenderer.invoke('voxel:setup-finish',input),
  onPullProgress: callback => { ipcRenderer.on('voxel:pull-progress',(_event,value)=>callback(value)); },
  getProviderCatalog: () => ipcRenderer.invoke('voxel:provider-catalog'),
  openProviderHelp: id => ipcRenderer.invoke('voxel:provider-help',id),
  listInstalledApps:()=>ipcRenderer.invoke('voxel:list-apps'),
  licenseStatus:()=>ipcRenderer.invoke('voxel:license-status'),
  activateLicense:token=>ipcRenderer.invoke('voxel:license-activate',token),
  removeLicense:()=>ipcRenderer.invoke('voxel:license-remove'),
  getSettings: () => ipcRenderer.invoke('voxel:get-settings'),
  saveSettings: input => ipcRenderer.invoke('voxel:save-settings', input),
  onSkin: callback => { ipcRenderer.on('voxel:skin', (_event,value) => callback(value)); },
  onState: callback => { ipcRenderer.on('voxel:state', (_event,state) => callback(state)); }
}));
